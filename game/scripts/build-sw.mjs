// Runs after `vite build`: writes dist/sw.js, the service worker that makes the web game
// playable offline. It precaches every built file and names its cache after a fingerprint of
// their contents, so any change to the game produces a new cache and players see
// "A new version of the game is ready · Reload". Nothing to bump by hand.
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dist = path.join(root, 'dist');
if (!fs.existsSync(path.join(dist, 'index.html'))) {
  console.error('dist/ is missing. Run "vite build" first.');
  process.exit(1);
}

// Files only crawlers or the host need are not cached on players' devices.
const SKIP = new Set(['sw.js', '_headers', '_redirects', 'og-image.png', 'robots.txt']);

function walk(dir, prefix = '') {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const rel = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (entry.isDirectory()) return walk(path.join(dir, entry.name), rel);
    return SKIP.has(rel) || rel.endsWith('.map') ? [] : [rel];
  });
}

const files = walk(dist).sort();
const hash = crypto.createHash('sha256');
for (const file of files) hash.update(file).update(fs.readFileSync(path.join(dist, file)));
const version = `tlw-${hash.digest('hex').slice(0, 12)}`;
const precache = ['./', ...files.map((f) => `./${f}`)];

const sw = `// Generated by scripts/build-sw.mjs. Do not edit: rebuild instead.
const CACHE = ${JSON.stringify(version)};
const PRECACHE = ${JSON.stringify(precache, null, 2)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('tlw-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('message', (event) => {
  if (event.data && event.data.type === 'SKIP_WAITING') self.skipWaiting();
});

// Cache first, so the page and its files always come from the same version.
self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;
  event.respondWith(
    caches.open(CACHE).then((cache) => {
      const lookup = req.mode === 'navigate' ? cache.match('./index.html') : cache.match(req, { ignoreSearch: true });
      return lookup.then(
        (hit) =>
          hit ||
          fetch(req).then((res) => {
            if (res && res.ok && res.type === 'basic' && req.mode !== 'navigate') cache.put(req, res.clone());
            return res;
          }),
      );
    }),
  );
});
`;
fs.writeFileSync(path.join(dist, 'sw.js'), sw);
console.log(`Service worker: ${version}, ${precache.length} files precached.`);
